/**
 * @file epd_font_data.c
 * @brief 字体数据文件（用户自行导入）
 * 
 * 使用说明：
 * 1. 本文件用于存放字模数据，由于字体数据过大，需要用户自行导入
 * 2. 从原 STM32 项目的 EPD_Font.h 中复制字模数据
 * 3. 按照下面的格式定义字体数据数组
 * 
 * 字模格式要求：
 * - 点阵格式：阴码
 * - 取模方式：逐行式
 * - 取模走向：顺向（高位在前）
 * - ASCII 码格式：C51
 * 
 * 字体数据结构：
 * - 前 6 字节为字体头：
 *   [0]: first_char (第一个字符 ASCII 码，通常 0x20)
 *   [1]: last_char (最后一个字符 ASCII 码，通常 0x7E)
 *   [2]: width (字体宽度，像素)
 *   [3]: height (字体高度，像素)
 *   [4-5]: char_bytes (每个字符的字节数，小端序)
 * - 后续为字模数据
 */

